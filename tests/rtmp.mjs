// RTMP output end to end: studio page -> helper -> ffmpeg -> local RTMP listener (ffmpeg) -> file.
// Run with the helper serving the app: node signaling-server/server.mjs --static . --port 8787
import { createRequire } from 'node:module';
import { spawn, execFileSync } from 'node:child_process';
import fs from 'node:fs';
const require = createRequire(`${process.env.PLAYWRIGHT_DIR || '/opt/node-tools/node_modules'}/`);
const { chromium } = require('playwright');
const OUT = process.argv[2] || '/tmp/webrtc-studio-rtmp-test.flv';
const r = []; const check = (n, ok, i = '') => { r.push(ok); console.log(`${ok ? 'PASS' : 'FAIL'}  ${n}${i ? `  (${i})` : ''}`); };
fs.rmSync(OUT, { force: true });
const sink = spawn('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-listen', '1', '-f', 'flv', '-i', 'rtmp://127.0.0.1:19350/app/testkey', '-c', 'copy', '-f', 'flv', OUT], { stdio: ['ignore', 'ignore', 'inherit'] });
await new Promise((res) => setTimeout(res, 800));
const b = await chromium.launch({ args: ['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream', '--autoplay-policy=no-user-gesture-required'] });
const page = await b.newPage(); const errs = []; page.on('pageerror', (e) => errs.push(e.message));
await page.goto('http://localhost:8787/index.html'); await page.waitForTimeout(1500);
await page.click('.tabs >> text=Outputs');
await page.locator('button', { hasText: '+ RTMP' }).click(); await page.waitForTimeout(300);
const card = page.locator('.card', { hasText: 'RTMP via helper' }).last();
check('RTMP card has no helper warning when the helper runs', !(await card.innerText()).includes('Install helper'));
await card.locator('input[placeholder^="rtmp://"]').fill('rtmp://127.0.0.1:19350/app'); await card.locator('input[placeholder^="rtmp://"]').dispatchEvent('change');
await card.locator('input[placeholder="Stream key"]').fill('testkey'); await card.locator('input[placeholder="Stream key"]').dispatchEvent('change');
await card.locator('button', { hasText: 'Start broadcast' }).click();
let state = '';
for (let i = 0; i < 30; i++) { await page.waitForTimeout(500); state = await page.evaluate(() => window.studio.outputs.all().find((o) => o.cfg.kind === 'rtmp')?.state); if (state === 'live') break; }
check('RTMP output goes live', state === 'live', state + ' ' + await page.evaluate(() => window.studio.outputs.all().find((o) => o.cfg.kind === 'rtmp')?.detail));
await page.waitForTimeout(8000);
const st = await page.evaluate(() => window.studio.outputs.all().find((o) => o.cfg.kind === 'rtmp')?.stats?.rtmp);
check('Stats show frames reaching the RTMP server', st?.frames > 100, JSON.stringify(st));
check('Not falling behind', st?.backlog < 2, String(st?.backlog));
const txt = await page.locator('.card', { hasText: 'RTMP via helper' }).last().innerText();
check('Card shows stats line', /behind/.test(txt) && /speed/.test(txt));
await page.locator('.card', { hasText: 'RTMP via helper' }).last().locator('button', { hasText: 'Stop broadcast' }).click();
await new Promise((res) => { sink.on('exit', res); setTimeout(res, 8000); });
const probe = fs.existsSync(OUT) ? execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'stream=codec_name,width,height:format=duration', '-of', 'json', OUT]).toString() : '{}';
const pj = JSON.parse(probe);
check('Recording has H.264 video', pj.streams?.some((s) => s.codec_name === 'h264' && s.width === 1920), probe.replace(/\s+/g, ' '));
check('Recording has AAC audio', pj.streams?.some((s) => s.codec_name === 'aac'));
check('Recording is at least 6 s long', Number(pj.format?.duration) >= 6, pj.format?.duration);
check('No page errors', errs.length === 0, errs.join(' | '));
console.log(`${r.filter(Boolean).length}/${r.length} passed`);
await b.close(); sink.kill();
